"""Write matching/scus_971.02.yaml, the splat configuration that splits the
retail file into assembly + data for the byte-identical matching build.

    python tools/gen_splat.py && python -m splat split matching/scus_971.02.yaml

Layout of the retail ELF (file offsets):
  0x00000  ELF header, program header, zero padding          -> bin
  0x01000  .text (+ .text.sceGsGetGParam/.sceGsResetGraph)   -> asm, one file per unit range
  0x27C00  .data   0x3EE00 .rodata   0x41C00 .rdata
  0x42000  .gcc_except_table   0x42D00 .lit4   0x42D80 .sdata (PT_LOAD ends 0x42E6B)
  .sbss 0x01041E80, .bss 0x01041F00 (NOBITS)
  0x42E6B  zero padding, .reginfo (not loaded), .shstrtab, section headers -> bin
"""
import json, os

import paths

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
units = json.load(open(os.path.join(ROOT, "ref", "units.json")))

TEXT_VRAM, TEXT_OFF = 0x01000000, 0x1000
ranges = sorted((int(lo, 16), int(hi, 16), u) for u, s in units.items() for lo, hi in s["ranges"])
seen = {}
text_subs = []
for lo, hi, u in ranges:
    seen[u] = seen.get(u, 0) + 1
    name = u if sum(1 for r in ranges if r[2] == u) == 1 else "%s_%d" % (u, seen[u])
    text_subs.append((lo - TEXT_VRAM + TEXT_OFF, "asm", "text/" + name))

Y = []
Y.append("# generated by tools/gen_splat.py - edit that script, not this file")
Y.append("name: SCUS_971.02 (Gran Turismo 3 US bootstrap)")
Y.append("sha1: 9ba003bddd9e03cae0440fd5f587f6201b25bd40")
Y.append("options:")
for k, v in [
    ("basename", "scus_971.02"),
    ("target_path", os.path.relpath(paths.retail_elf(), os.path.join(ROOT, "matching")).replace("\\", "/")),
    ("base_path", "."),
    ("platform", "ps2"),
    ("compiler", "EEGCC"),
    ("build_path", "build"),
    ("asm_path", "asm"),
    ("src_path", "src"),
    ("ld_script_path", "scus_971.02.ld"),
    ("symbol_addrs_path", "symbol_addrs.txt"),
    ("undefined_funcs_auto_path", "undefined_funcs_auto.txt"),
    ("undefined_syms_auto_path", "undefined_syms_auto.txt"),
    ("find_file_boundaries", "False"),
    ("gp_value", "0x01049CF0"),
    ("create_asm_dependencies", "False"),
    ("use_legacy_include_asm", "False"),
    ("asm_function_macro", "glabel"),
    ("asm_jtbl_label_macro", "jlabel"),
    ("asm_data_macro", "dlabel"),
    ("generate_asm_macros_files", "True"),
    ("emit_subalign", "False"),          # retail units start 8-aligned; .align in each file handles it
    ("string_encoding", "ASCII"),
    ("rodata_string_guesser_level", "2"),
    ("data_string_guesser_level", "2"),
    ("disasm_unknown", "True"),
    ("ld_bss_is_noload", "True"),
    ("ld_align_section_vram_end", "False"),
    ("ld_align_segment_vram_end", "False"),
]:
    Y.append("  %s: %s" % (k, v))
Y.append("  section_order: [\".text\", \".data\", \".rodata\", \".rdata\", \".gcc_except_table\", \".lit4\", \".sdata\", \".sbss\", \".bss\"]")
Y.append("segments:")
Y.append("  - [0x0, bin, elf_header]")
Y.append("  - name: main")
Y.append("    type: code")
Y.append("    start: 0x1000")
Y.append("    vram: 0x01000000")
Y.append("    bss_size: 0xC029          # end of loaded data 0x01041E6B .. _end 0x0104DE94")
Y.append("    subsegments:")
for off, t, n in text_subs:
    Y.append("      - [0x%05X, %s, %s]" % (off, t, n))
for off, t, n in [(0x27C00, "data", "data/data"), (0x3EE00, "rodata", "data/rodata"),
                  (0x41C00, "rdata", "data/rdata"), (0x42000, "gcc_except_table", "data/gcc_except_table"),
                  (0x42D00, "lit4", "data/lit4"), (0x42D80, "sdata", "data/sdata"),
                  # .sdata is 0xEB bytes: spimdisasm drops a trailing partial word, so the
                  # last 3 bytes ("%s\0" at 0x01041E68) are their own subsegment
                  (0x42E68, "sdata", "data/sdata_tail")]:
    Y.append("      - [0x%05X, %s, %s]" % (off, t, n))
# retail .sbss/.bss are 128-aligned (0x01041E80, 0x01041F00)
Y.append("      - { start: 0x42E6B, type: sbss, vram: 0x01041E80, name: data/sbss, align: 0x80 }")
Y.append("      - { start: 0x42E6B, type: bss, vram: 0x01041F00, name: data/bss, align: 0x80 }")
Y.append("  - [0x42E6B, bin, elf_trailer]")
Y.append("  - [0x43194]")
os.makedirs(os.path.join(ROOT, "matching"), exist_ok=True)
open(os.path.join(ROOT, "matching", "scus_971.02.yaml"), "w", newline="\n").write("\n".join(Y) + "\n")
print("wrote matching/scus_971.02.yaml with %d text subsegments" % len(text_subs))
