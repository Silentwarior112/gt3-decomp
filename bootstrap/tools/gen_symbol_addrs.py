"""Write matching/symbol_addrs.txt (splat format) from the decomp's function
table: every function start with an assembler-safe name and its size.

    python tools/gen_symbol_addrs.py

Names: the FUNC marker's identifier when it is a plain C identifier (the real
symbol, e.g. sceSifBindRpc), otherwise func_<ADDR>. Sizes exclude trailing
alignment padding, so splat does not fold a `nop` into the function.
"""
import json, os, re, struct

import paths

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
BIN = paths.retail_elf()
MARK = re.compile(r"^\s*(?://|/\*)\s*FUNC\s+0x(01[0-9A-Fa-f]{6})\b\s*(.*?)\s*(?:\*/)?\s*$")
CXX_WORDS = {"operator", "typeinfo", "non", "virtual", "vtable", "thunk", "static", "const",
             "unsigned", "signed", "void", "int", "char", "struct", "class", "template"}

img = open(BIN, "rb").read()
funcs = json.load(open(os.path.join(ROOT, "ref", "funcs.json")))

def word(a):
    return struct.unpack_from("<I", img, 0x1000 + a - 0x01000000)[0]

def has_delay(w):
    op = w >> 26
    return op in (1, 2, 3, 4, 5, 6, 7, 0x14, 0x15, 0x16, 0x17) or (op == 0 and (w & 0x3F) in (8, 9)) or \
        (op in (0x11, 0x12) and ((w >> 21) & 31) == 8)

names = {}
for sub in ("src", "sdk", "runtime"):
    for dp, _, fns in os.walk(os.path.join(ROOT, sub)):
        for fn in fns:
            if fn.endswith((".c", ".cpp", ".cc", ".S")):
                for line in open(os.path.join(dp, fn), encoding="utf-8", errors="replace"):
                    m = MARK.match(line)
                    if m:
                        tok = m.group(2).split()[0] if m.group(2).split() else ""
                        # a plain identifier names the real symbol; C++ text such
                        # as "operator new(unsigned int)" or "typeinfo function
                        # for X" does not (its first word is a keyword)
                        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", tok) and tok not in CXX_WORDS:
                            names[int(m.group(1), 16)] = tok

used = set()
out = ["// generated by tools/gen_symbol_addrs.py from ref/funcs.json and the FUNC markers"]
for f in sorted(funcs, key=lambda f: f["start"]):
    a, e = f["start"], f["end"]
    n = (e - a) // 4
    while n > 1 and word(a + 4 * (n - 1)) == 0 and not has_delay(word(a + 4 * (n - 2))):
        n -= 1
    nm = names.get(a) or "func_%08X" % a
    if nm in used:
        nm = "%s_%08X" % (nm, a)
    used.add(nm)
    out.append("%s = 0x%08X; // type:func size:0x%X" % (nm, a, 4 * n))
os.makedirs(os.path.join(ROOT, "matching"), exist_ok=True)
open(os.path.join(ROOT, "matching", "symbol_addrs.txt"), "w", newline="\n").write("\n".join(out) + "\n")
print("%d functions written" % (len(out) - 1))
