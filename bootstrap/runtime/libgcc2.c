/* libgcc2.c - GCC 2.9x-ee libgcc2 pieces of the GT3 US bootstrap
 * (BOOTSTRAP_SCUS-97102) other than the exception-handling block (L_eh, see
 * runtime/eh.c):
 *
 *   L__main   0x01016FD8..0x01017100  __do_global_dtors, __do_global_ctors, __main
 *   L_muldi3  0x01018070..0x010180D0  __muldi3
 *   L_pure    0x010180D0..0x010180D8  __pure_virtual
 *
 * libgcc2.c is built once per L_xxx macro, each into its own object; the
 * linker placed __main.o and _eh.o right after libmc, and _muldi3.o/_pure.o
 * right after _eh.o (just before exception.o at 0x010180D8).
 *
 * EE build specifics visible in the machine code:
 *   - no INIT_SECTION: the ctor/dtor lists are walked by __main at run time;
 *   - __do_global_ctors does NOT register a __do_global_dtors atexit handler
 *     and does NOT call __register_frame_info (crtbegin's reg_frame, entry
 *     0x010000C8 of __CTOR_LIST__, does the frame registration instead);
 *   - __do_global_dtors does not deregister the frame info either;
 *   - inhibit_libc: __pure_virtual prints nothing.
 */
#include "types.h"
#include "cxxrt.h"

typedef void (*func_ptr)(void);

/* Constructor / destructor lists (very start of .data), generated by collect2
 * at link time; defined in src/crtbegin.c (main unit) and declared in cxxrt.h
 * as `void (*__CTOR_LIST__[])(void)` (= func_ptr[]).
 * Format: word 0 = count (or -1 = "count the entries"), then the function
 * pointers, then a 0 terminator.  In this binary both have count 3:
 *   __CTOR_LIST__ @0x01026C98 = {3, 0x01003CC0, 0x01011480, 0x010000C8 (reg_frame), 0}
 *   __DTOR_LIST__ @0x01026CB0 = {3, 0x01003C90, 0x01011458, 0x01000108 (dereg_frame), 0} */

/* ------------------------------------------------------------------------ */
/* L__main                                                                  */
/* ------------------------------------------------------------------------ */

// FUNC 0x01016FD8 __do_global_dtors
/* Run the global destructors in list order: while (*p) { p++; (*(p-1))(); }.
 * The cursor p is a static, so a second call resumes after the destructors
 * that already ran; it is stored back before each call.
 * NOTE: the count word at __DTOR_LIST__[0] is ignored; the walk stops at the
 * 0 terminator.  No callers in the binary (the bootstrap leaves via ExecPS2,
 * never through exit()), and nothing registers it with atexit. */
void __do_global_dtors(void)
{
    static func_ptr *p = __DTOR_LIST__ + 1;   /* @0x0103BE90 (.data), init 0x01026CB4 */

    while (*p) {
        p++;
        (*(p - 1))();
    }
}

// FUNC 0x01017030 __do_global_ctors
/* Run the global constructors in REVERSE list order (GCC's DO_GLOBAL_CTORS_BODY):
 * nptrs = __CTOR_LIST__[0]; if that is -1 the entries are counted up to the
 * 0 terminator; then __CTOR_LIST__[nptrs] .. __CTOR_LIST__[1] are called.
 * Here nptrs = 3, so the calls are 0x010000C8 (crtbegin reg_frame: EH frame
 * registration), then 0x01011480, then 0x01003CC0.
 * Reached only by the tail jump in __main (the mapping pass missed its start;
 * boundary fix 0x01017030).  No atexit(__do_global_dtors) in this build. */
void __do_global_ctors(void)
{
    unsigned long nptrs = (unsigned long)__CTOR_LIST__[0];
    unsigned i;

    if (nptrs == (unsigned long)-1)
        for (nptrs = 0; __CTOR_LIST__[nptrs + 1] != 0; nptrs++)
            ;

    for (i = nptrs; i >= 1; i--)        /* unsigned: loop while i != 0 */
        __CTOR_LIST__[i]();
}

// FUNC 0x010170E0 __main
/* Called by GCC at the top of main() (0x01000538); also referenced from the
 * .sdata word 0x01041D80.  Runs the global constructors exactly once
 * (supports recursive main).  The call to __do_global_ctors is a tail jump
 * (`j 0x01017030` with the guard store in the delay slot). */
void __main(void)
{
    static int initialized;             /* @0x01049F40 (.bss) */

    if (!initialized) {
        initialized = 1;
        __do_global_ctors();
    }
}

