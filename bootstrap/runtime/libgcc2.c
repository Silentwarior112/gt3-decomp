typedef int                SItype;
typedef unsigned int       USItype;
typedef long long          DItype;
typedef unsigned long long UDItype;

/* Little-endian double-word view (LIBGCC2_WORDS_BIG_ENDIAN = 0). */
struct DIstruct { SItype low, high; };
typedef union {
    struct DIstruct s;
    DItype ll;
} DIunion;

/* 32x32->64 unsigned multiply: a single `multu` + mflo/mfhi on the R5900. */
/* 32x32->64 unsigned multiply as the binary does it: one `multu`, result
 * in HI:LO (libgcc's longlong.h umul_ppmm for MIPS).  Written in asm on
 * purpose: as a C widening multiply, a compiler that does not recognise the
 * pattern (GCC 14 at -O0) emits a DImode multiply, i.e. a call to
 * __muldi3 itself, which then recurses forever. */
static inline UDItype __umulsidi3(USItype u, USItype v)
{
    USItype hi, lo;

    __asm__("multu %2, %3\n\tmfhi %0\n\tmflo %1"
            : "=r"(hi), "=r"(lo) : "r"(u), "r"(v) : "hi", "lo");
    return ((UDItype)hi << 32) | lo;
}

// FUNC 0x01018070 __muldi3
/* 64x64->64 multiply (the R5900 has no dmult).  low*low via `multu`, the two
 * cross products low(u)*high(v) and high(u)*low(v) via the EE's 3-operand
 * `mult` on pipeline 0 and `mult1` on pipeline 1, added into the high word.
 * Callers: bignum code (0x01007B70) and libgcc's __muldf3 area (0x01025538). */
DItype __muldi3(DItype u, DItype v)
{
    DIunion w;
    DIunion uu, vv;

    uu.ll = u;
    vv.ll = v;

    w.ll = __umulsidi3(uu.s.low, vv.s.low);
    w.s.high += ((USItype)uu.s.low * (USItype)vv.s.high
                 + (USItype)uu.s.high * (USItype)vv.s.low);

    return w.ll;
}

