// FUNC 0x010180D0 __pure_virtual
/* Fills the pure-virtual slots of abstract-class vtables: both method slots of
 * ImageLoader::Source's vtable (the .rodata words 0x0103E26C / 0x0103E274,
 * vtable @0x0103E258).  inhibit_libc build, so no "pure virtual method called"
 * message: the whole body is a tail jump `j __terminate`. */
void __pure_virtual(void)
{
    __terminate();
}
