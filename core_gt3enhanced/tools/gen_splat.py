"""Write ref/splat/core.yaml and its symbol file: the splat configuration that
disassembles the main executable into one GNU-as file per work unit
(ref/splat/asm/<unit>.s, the input of tools/m2c_drafts.py) plus the data.

    python tools/gen_splat.py && python -m splat split ref/splat/core.yaml

Function starts and sizes come from ref/funcs.json, so spimdisasm uses our
boundaries; data names from ref/data_symbols.csv.
"""
import csv
import json
import os

import coreelf as E
import paths

R = paths.REF
SP = os.path.join(R, "splat")
os.makedirs(SP, exist_ok=True)
units = json.load(open(os.path.join(R, "units.json")))
funcs = json.load(open(os.path.join(R, "funcs.json")))


def off(va):
    return va - E.BASE + E.FOFF


with open(os.path.join(SP, "symbol_addrs.txt"), "w", newline="\n") as fh:
    for f in funcs:
        a = int(f["start"], 16)
        fh.write("F_%08X = 0x%08X; // type:func size:0x%X\n" % (a, a, f["size"]))
    p = os.path.join(R, "data_symbols.csv")
    for r in csv.DictReader(open(p, encoding="utf-8")):
        a = int(r["addr"], 16)
        if E.TEXT_HI <= a < E.BSS_END:
            nm = r["name"].replace("$", "_")
            fh.write("%s = 0x%08X;\n" % (nm, a))

img_len = E.IMG_END - E.BASE
Y = []
Y.append("# generated by tools/gen_splat.py")
Y.append("name: BASE_SCUS-97102 (Gran Turismo 3 A-Spec US main executable)")
Y.append("options:")
for k, v in [
    ("basename", "core"),
    ("target_path", os.path.relpath(paths.retail_elf(), SP).replace("\\", "/")),
    ("base_path", "."),
    ("platform", "ps2"),
    ("compiler", "EEGCC"),
    ("build_path", "build"),
    ("asm_path", "asm"),
    ("src_path", "src"),
    ("ld_script_path", "core.ld"),
    ("symbol_addrs_path", "symbol_addrs.txt"),
    ("undefined_funcs_auto_path", "undefined_funcs_auto.txt"),
    ("undefined_syms_auto_path", "undefined_syms_auto.txt"),
    ("find_file_boundaries", "False"),
    ("gp_value", "0x%08X" % E.GP),
    ("create_asm_dependencies", "False"),
    ("asm_function_macro", "glabel"),
    ("asm_jtbl_label_macro", "jlabel"),
    ("asm_data_macro", "dlabel"),
    ("generate_asm_macros_files", "True"),
    ("string_encoding", "ASCII"),
    ("rodata_string_guesser_level", "2"),
    ("data_string_guesser_level", "2"),
    ("disasm_unknown", "True"),
    ("ld_bss_is_noload", "True"),
    ("asm_emit_size_directive", "False"),
]:
    Y.append("  %s: %s" % (k, v))
Y.append("  section_order: [\".text\", \".data\", \".rodata\", \".bss\"]")
Y.append("segments:")
Y.append("  - [0x0, bin, elf_header]")
Y.append("  - name: main")
Y.append("    type: code")
Y.append("    start: 0x1000")
Y.append("    vram: 0x%08X" % E.BASE)
Y.append("    bss_size: 0x%X" % (E.BSS_END - E.SBSS))
Y.append("    subsegments:")
for u, s in units.items():
    lo = int(s["ranges"][0][0], 16)
    Y.append("      - [0x%06X, asm, %s]" % (off(lo), u))
Y.append("      - [0x%06X, bin, eh_tables]" % off(E.TEXT_HI))
Y.append("      - [0x%06X, rodata, data]" % off(E.EH_FRAME_HI))
# spimdisasm emits whole words: the image ends 3 bytes past one ("%s\0" at
# 0x003531E0), so those go in as raw .rodata of their own
tail = (E.IMG_END - E.EH_FRAME_HI) % 4
if tail:
    Y.append("      - [0x%06X, rodatabin, data_tail]" % off(E.IMG_END - tail))
Y.append("      - { start: 0x%06X, type: bss, vram: 0x%08X, name: bss }" % (off(E.IMG_END), E.SBSS))
Y.append("  - [0x%06X, bin, elf_trailer]" % off(E.IMG_END))
Y.append("  - [0x%06X]" % os.path.getsize(paths.retail_elf()))
open(os.path.join(SP, "core.yaml"), "w", newline="\n").write("\n".join(Y) + "\n")
print("wrote ref/splat/core.yaml: %d text subsegments" % len(units))
