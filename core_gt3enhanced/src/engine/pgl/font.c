/* font.c - unit u114, 0x00249B28..0x0024B0D8 (G001, no FDE: C).
 *
 * The graphics library's bitmap text renderer.  State lives in the library
 * block g_002F72C0 (GsLibState, +0x68..+0xE0).  font_begin opens a GIF
 * packet at the drawing context's write pointer (a DMA tag + VIF DIRECT,
 * written by font_flush when the packet is closed) with the font texture's
 * registers; every glyph is a sprite (UV, XYZF3, UV, XYZF2) appended to a
 * "run" whose REGLIST GIF tag is patched when the PRIM or the colour
 * changes.  Codes >= 0x80 are two bytes: a first byte >= 0xA1 selects the
 * kanji font (4-bit glyphs uploaded one by one into a VRAM cell, drawn with
 * GS context 2), else the byte pair is mapped through g_kanaPages to a code
 * of the bitmap font.  Kerning comes from per-row glyph profiles (MMI).
 * The C++ side is T496 Font (u109): Font::loadFile / loadKanjiFont load the
 * files relocated here, Font::begin selects the face (font_set) and the
 * kanji font (font_set_kanji) and opens the packet.  The printf side
 * follows in fontprint.c.
 */
