// FUNC 0x00249B40 fontset_relocate
// Relocates a loaded font-set file in place (pointers are relative to the
// address in fs->self): the textures (each relocated by tex1_relocate), the
// faces, their glyph tables and kerning profiles; every face gets its
// texture (font->tex = fs->tex[i]).  Nothing happens if already in place.
// Caller: Font::loadFile (T496).
// 94.0%: the glyph loop's base pointer is copied in the inner loop's
// preheader in retail (daddu a3,v1 after the exit test), here right after
// its store, and the inner loop's registers follow; tried g as a local, a
// for-init, font->glyphs[j], &glyphs[j] pointers, an inline helper,
// declaration orders; session 2: g taken inside the loop body (gets the
// copy into the preheader, but coalesced: 90%), j / code for-inits.
FontSet *fontset_relocate(FontSet *fs)
{
    s32 delta = (u8 *)fs - (u8 *)fs->self;
    int i;

    if (delta == 0)
        return fs;
    fs->self = fs;
    RELOC(fs->unk_08, delta);
    RELOC(fs->tex, delta);
    for (i = 0; i < fs->count; i++) {
        RELOC_ALWAYS(fs->tex[i], delta);
        tex1_relocate(fs->tex[i]);
    }
    RELOC(fs->fonts, delta);
    for (i = 0; i < fs->count; i++) {
        if (fs->fonts[i] != NULL) {
            PglFont *font;

            RELOC(fs->fonts[i], delta);
            font = fs->fonts[i];
            RELOC(font->name, delta);
            if (font->glyphs != NULL) {
                FontGlyph *g;
                int code, j = 0;

                RELOC(font->glyphs, delta);
                g = font->glyphs;
                for (code = font->first; code <= font->last; code++, j++) {
                    RELOC(g[j].left, delta);
                    RELOC(g[j].right, delta);
                }
            }
            fs->fonts[i]->tex = fs->tex[i];
        }
    }
    return fs;
}

// FUNC 0x00249CE8 kanjifile_relocate
// The same relocation for the kanji font file (KanjiFontFile, FontSet's header
// layout): +0x08, the KanjiFont records at +0x14 (count at +0x10; each
// record's data, map and +0x14) and the CLUT block at +0x18.  Caller:
// Font::loadKanjiFont (T496), which keeps record 0 and the CLUTs for
// font_set_kanji.
KanjiFontFile *kanjifile_relocate(KanjiFontFile *f)
{
    s32 delta = (u8 *)f - (u8 *)f->self;
    int i, n;

    if (delta == 0)
        return f;
    f->self = f;
    RELOC(f->unk_08, delta);
    if (f->fonts != NULL) {
        RELOC(f->fonts, delta);
        n = f->count;
        for (i = 0; i < n; i++) {
            if (f->fonts[i] != NULL) {
                RELOC(f->fonts[i], delta);
                RELOC(f->fonts[i]->data, delta);
                RELOC(f->fonts[i]->map, delta);
                RELOC(f->fonts[i]->unk_14, delta);
            }
        }
    }
    RELOC(f->cluts, delta);
    return f;
}

