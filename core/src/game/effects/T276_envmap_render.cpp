/* the sky (turned by the environment's angles), then the course: the
 * parts listed in parts ({n, part[n]}), or all of it if parts is NULL */
// FUNC 0x001D8288 envmapDrawScene
void envmapDrawScene(CourseData *course, CameraBase *cam, u16 *parts)
{
    u16 n;

    gfx_enable(PGL_CAP_DEPTH_TEST);
    gfx_disable(PGL_CAP_ALPHA_TEST);
    gs_clear_buffers(PGL_CLEAR_COLOR | PGL_CLEAR_DEPTH);
    pgl_push_matrix();
    cam->applyView();                       /* the view */
    pgl_push_matrix();
    vu0_reset_translation();
    vu0_rotate_x(course->env->skyRotX);
    vu0_rotate_y(course->env->skyRotY);
    modelset_draw_all(course->envSky);
    pgl_pop_matrix();
    gs_clear_buffers(PGL_CLEAR_DEPTH);
    if (parts != NULL) {
        n = *parts;
        modelset_begin_draw(course->envModel);
        parts++;
        while (n-- != 0)
            modelset_run_part(course->envModel, *parts++);
        modelset_end_draw(course->envModel);
    } else {
        modelset_draw_all(course->envModel);
    }
    pgl_pop_matrix();
}

/* A work buffer of psm, ENVMAP_WORK_WIDTH x ENVMAP_WORK_HEIGHT.  (? an inline
 * helper in the original: retail stores the Z buffer's fields through the
 * register that holds its address, as the inline's argument; written in
 * place they fold onto $sp and are scheduled before the colour buffer's.) */
static inline void envmapSetFormat(GSBuffer *b, int psm)
{
    b->psm = psm;
    b->width = ENVMAP_WORK_WIDTH;
    b->height = ENVMAP_WORK_HEIGHT;
}

/* vram < 0: the two work buffers get VRAM of their own, else they are put
 * at vram (the colour buffer, then the Z buffer) */
// FUNC 0x001D83A8 envmapRender
void envmapRender(GSBuffer *target, CourseData *course, DynamicEnvmapCamera *cam, int vram)
{
    u16 *parts;
    int view;
    f32 viewF;

    pgl_push_attrib(PGL_ATTR_DRAW_BUFFER | PGL_ATTR_DEPTH | PGL_ATTR_TARGET_B |
                    PGL_ATTR_VIEWPORT | PGL_ATTR_SCISSOR);     /* 0x887 */
    F_001A8208(course->env);
    target->setDrawBuffer();
    gs_set_clear_color(0x80000000);
    gs_clear_buffers(PGL_CLEAR_COLOR);

    GSBuffer color;                         /* sp+0x00 */
    GSBuffer depth;                         /* sp+0x40 */
    envmapSetFormat(&color, ENVMAP_PSMCT32);
    envmapSetFormat(&depth, ENVMAP_PSMZ24);
    if (vram < 0) {
        color.allocVram();
        depth.allocVram();
    } else {
        color.setAddr(vram);
        depth.setAddr(vram + color.vramSize());
    }

    parts = NULL;
    if (course->envVision != NULL)
        parts = vision_nearest(course->envVision, cam->worldX, cam->worldY, cam->worldZ)->parts;

    for (view = 0; view < ENVMAP_VIEWS; view++) {
        /* the scene, turned view * 120 degrees about z */
        pgl_matrix_mode(PGL_MTX_PROJECTION);
        vu0_load_identity_regs();
        pgl_frustum(-0.5f, 0.5f, -0.753778f, 0.904534f, 0.005f, 200.0f, 0.1599f);
        pgl_matrix_mode(PGL_MTX_MODELVIEW);
        vu0_load_identity_regs();
        vu0_rotate_x(79.97501f);
        viewF = (f32)view;
        vu0_rotate_z(viewF * -120.0f);
        color.setDrawBuffer();
        depth.setZBuffer();
        envmapDrawScene(course, cam, parts);
        gfx_texflush();

        /* the picture onto the target through the GTM1 model */
        target->setDrawBuffer();
        color.setTexture();
        pgl_matrix_mode(PGL_MTX_PROJECTION);
        vu0_load_identity_regs();
        pgl_ortho(-0.9f, 0.9f, -0.9f, 0.9f, -1.0f, 1.0f);
        pgl_matrix_mode(PGL_MTX_MODELVIEW);
        vu0_load_identity_regs();
        vu0_rotate_z(240.0f - viewF * 120.0f);
        modelset_set_env_tex(NULL);
        modelset_set_state5(0);
        modelset_draw_all(ENVMAP_MODEL);
        modelset_set_state5(1);
    }
    gfx_texflush();
    pgl_pop_attrib();
}                                           /* ~depth, ~color: GSBuffer::~GSBuffer(.., 2) */

/* the camera is a local */
// FUNC 0x001D8698 envmapUpdate
void envmapUpdate(GSBuffer *target, CourseData *course, CameraManager *cm, int vram, f32 t)
{
    DynamicEnvmapCamera cam;

    cam.followView(cm, t);
    envmapRender(target, course, &cam, vram);
}                                           /* implicit: ~cam, the implicit destructor: CameraBase::~CameraBase(&cam, 2) */
