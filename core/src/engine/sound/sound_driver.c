// FUNC 0x00268340 engn_relocate
/* Relocates an ENGN bank loaded at b: pointers by (b - b->self); with a
 * non-zero spu_base the segments' SPU addresses by (spu_base - old base).
 * NULL if the magic does not match.  Caller GTSOUNDINSTRUMENT::transfer. */
EngnBank *engn_relocate(EngnBank *b, u32 spu_base)
{
    int delta;
    int i;

    if (b->magic != ENGN_MAGIC)
        return NULL;
    delta = (u8 *)b - (u8 *)b->self;
    b->self = b;
    SND_RELOC(b->samples, delta);
    for (i = 0; i < 2; i++) {
        if (b->set[i].segs != NULL)
            SND_RELOC(b->set[i].segs, delta);
    }
    if (spu_base != 0) {
        u32 old_base = b->spuBase;
        int spu_delta;

        b->spuBase = spu_base;
        spu_delta = spu_base - old_base;
        for (i = 0; i < 2; i++) {
            EngnSeg *seg = b->set[i].segs;
            u32 j;

            for (j = 0; j < b->set[i].count; j++, seg++)
                seg->addr += spu_delta;
        }
    }
    return b;
}

