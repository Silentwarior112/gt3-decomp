// FUNC 0x00268A60 seq_unlink
/* Removes the sequence from the playing list if it is there. */
void seq_unlink(Sequence *seq)
{
    /* do / while with the early return (retail's loop has no entry test);
     * open: retail keeps %hi(g_002FF958) in $v1 and copies it to $a2 for
     * the final store (head / n then in $v1 / $v0); ours allocates the
     * %hi to $a2 directly. */
    Sequence *head = g_002FF958.head;
    Sequence *n, *prev = NULL;

    if (head == NULL)
        return;
    n = head;
    do {
        if (n == seq) {
            if (prev != NULL)
                prev->next = n->next;
            else
                head = n->next;
            break;
        }
        prev = n;
        n = n->next;
    } while (n != NULL);
    g_002FF958.head = head;
}

// FUNC 0x00268AB0 seq_start
/* (Re)starts a sequence player on SEQG entry e with instrument bank
 * `bank` (music_play, which links it): unlinked, volumes, step =
 * SEQ_TICKS_PER_SEC / frame rate, tempo, and each of the 16 tracks at its
 * first event after reading the leading delta time (big-endian 7-bit
 * groups, bit 7 = more). */
void seq_start(Sequence *seq, SeqgEntry *e, InstBank *bank)
{
    int k;
    int step;

    seq_unlink(seq);
    seq->volume = e->volume;
    seq->bank = bank;
    seq->next = NULL;
    seq->volEff = (g_002FF958.volume * e->volume) >> 14;
    step = SEQ_TICKS_PER_SEC / (int)g_002FF958.frameRate;
    seq->frameStep = step;
    seq->tickAcc = step;
    seq->tempo = e->tempo;
    for (k = 0; k < SEQ_NUM_TRACKS; k++) {
        SeqTrack *track = &seq->tracks[k];
        u8 *pos = e->tracks[k];
        u32 byte;

        /* The first delta byte through a local, the rest through
         * track->pos (retail reloads pos / wait in the loop).  Left: retail
         * stores wait before the incremented pos (pos in the beqz slot). */
        track->pos = pos;
        track->wait = *pos++;
        track->pos = pos;
        if (track->wait & 0x80) {
            track->wait &= 0x7F;
            do {
                byte = *track->pos;
                track->pos++;
                track->wait = (track->wait << 7) + (byte & 0x7F);
            } while (byte & 0x80);
        }
        track->volume = 0x4000;
        track->volScaled = seq->volEff;
        track->bend = 0;
        track->pan = 0;
        track->program = 0;
        track->loopDepth = -1;
    }
}

