/* Allocates a voice for p->priority with interrupts off, stores its index
 * in *handle (if given), and if one was found binds it to the handle
 * (owner, state 1) and starts it with p.  ($a2 = 1 at the snd_voice_start
 * call is the constant of the state store, not an argument: u124's
 * snd_voice_start sets $a2 itself.) */
void snd_play_voice(s8 *handle, SndVoiceParam *p)
{
    int intr_on = intr_suspend();
    int idx = snd_voice_alloc(p->priority);

    if (handle != NULL)
        *handle = idx;
    if (idx >= 0) {
        SndVoice *voice = &g_002FF168.voices[idx];

        voice->state = 1;
        voice->owner = handle;
        snd_voice_start(idx, p);
    }
    if (intr_on)
        U123_EI();
}

// FUNC 0x00268630 inst_relocate
/* Relocates an INST bank: its three pointers and the program pointer
 * table by (b - b->self); with a non-zero spu_base the zones' SPU
 * addresses (in 8-byte units) by (spu_base - old base) >> 3.  NULL if the
 * magic does not match.  Caller GTSOUNDINSTRUMENT::transfer. */
InstBank *inst_relocate(InstBank *b, u32 spu_base)
{
    int delta;
    u32 j;

    if (b->magic != INST_MAGIC)
        return NULL;
    delta = (u8 *)b - (u8 *)b->self;
    SND_RELOC(b->samples, delta);
    SND_RELOC(b->zones, delta);
    b->self = b;
    SND_RELOC(b->programs, delta);
    for (j = 0; j < b->nprograms; j++)
        SND_RELOC(b->programs[j], delta);
    if (spu_base != 0) {
        u32 spu_delta = spu_base - b->spuBase;

        b->spuBase = spu_base;
        for (j = 0; j < b->nzones; j++)
            b->zones[j].addr += spu_delta >> 3;
    }
    return b;
}

