// FUNC 0x00267D18 engine_layer_pitch
/* pitch = (seg->pitch * rpm / seg->base_rpm) * es->pitch >> 12 (unsigned
 * divide; trap on base 0), at least 1; with `smooth` clamped to
 * [old / 2, old * 2]. */
void engine_layer_pitch(GtSoundVoice *es, int i, int rpm, int smooth)
{
    /* es->layer[i] written out at each use (retail recomputes es + i * 16
     * for the final store). */
    EngnSeg *seg = &es->segs[es->layer[i].seg];
    u32 pitch;

    pitch = (u32)(seg->pitch * rpm) / (u32)(int)seg->base_rpm;
    pitch = (pitch * es->pitch) >> 12;
    if (pitch == 0)
        pitch = 1;
    if (smooth) {
        u32 old = es->layer[i].pitch;

        if (old * 2 < pitch)
            pitch = old * 2;
        else if (pitch < (old >> 1))
            pitch = old >> 1;
    }
    es->layer[i].pitch = pitch;
}

// FUNC 0x00267D98 engine_layer_volume
/* Crossfade factor fade (0x4000 = full): when the other layer plays a
 * segment and rpm is below this segment's range, fade = (rpm - other.hi) /
 * (lo - other.hi); above it, fade = (other.lo - rpm) / (other.lo - hi)
 * (both << 14, signed divide).  fade < 0 -> 0; gain = sin(fade * 90 deg)
 * (g_snd_sine[fade >> 4], 4096 = 1) * 0x3FFF >> 12, times the segment
 * volume >> 14, times the sound's volL / volR >> 14.  With `smooth` each
 * magnitude may move at most 0x1000 from the old one (sign of the new value
 * kept). */
void engine_layer_volume(GtSoundVoice *es, int i, int rpm, int smooth)
{
    /* One variable for the fade and then the gain (retail keeps both in
     * $a0); es->layer[i] written out at each use; separate sign flags and
     * old magnitudes per side. */
    EngnSeg *seg = &es->segs[es->layer[i].seg];
    int fade = ENGINE_FADE_FULL;
    int volL, volR;

    if (es->layer[(i + 1) & 1].seg >= 0) {
        EngnSeg *oseg = &es->segs[es->layer[(i + 1) & 1].seg];

        if (rpm < seg->lo)
            fade = ((rpm - oseg->hi) << 14) / (seg->lo - oseg->hi);
        else if (seg->hi < rpm)
            fade = ((oseg->lo - rpm) << 14) / (oseg->lo - seg->hi);
    }
    if (!(fade > -1))
        fade = 0;
    fade = (g_snd_sine[((u32)fade >> 4) & 0xFFF] * SND_VOL_FULL) >> 12;
    fade = (fade * seg->vol) >> 14;         /* the gain */
    volL = (es->volL * fade) >> 14;
    volR = (es->volR * fade) >> 14;
    if (smooth) {
        int oldL = es->layer[i].volL;
        int oldR = es->layer[i].volR;
        int negL, negR;

        negL = 0;
        if (volL < 0) {
            negL = 1;
            volL = -volL;
        }
        oldL = (oldL > -1) ? oldL : -oldL;
        if (oldL + ENGINE_SLEW_VOL < volL)
            volL = oldL + ENGINE_SLEW_VOL;
        else if (volL < oldL - ENGINE_SLEW_VOL)
            volL = oldL - ENGINE_SLEW_VOL;
        if (negL)
            volL = -volL;

        negR = 0;
        if (volR < 0) {
            negR = 1;
            volR = -volR;
        }
        oldR = (oldR > -1) ? oldR : -oldR;
        if (oldR + ENGINE_SLEW_VOL < volR)
            volR = oldR + ENGINE_SLEW_VOL;
        else if (volR < oldR - ENGINE_SLEW_VOL)
            volR = oldR - ENGINE_SLEW_VOL;
        if (negR)
            volR = -volR;
    }
    es->layer[i].volL = volL;
    es->layer[i].volR = volR;
}

