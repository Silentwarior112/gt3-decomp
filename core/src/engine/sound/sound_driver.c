// FUNC 0x002687B0 snd_note_to_pitch
/* note, base: 8.8 semitones (OCTAVE = 0xC00).  pitch = table[n / 8]
 * (0x4000 * 2^(n / 3072)) shifted by the octave, starting at >> 2 (base
 * note = 0x1000, 1.0 at 44.1 kHz). */
u16 snd_note_to_pitch(int note, int base)
{
    int n = note - base;
    int octave = -2;
    u16 pitch;

    if (n < 0) {
        do {
            n += OCTAVE;
            octave--;
        } while (n < 0);
    } else {
        while (n >= OCTAVE) {
            n -= OCTAVE;
            octave++;
        }
    }
    pitch = g_snd_pitch_octave[(u32)n >> 3];
    if (octave > 0)
        return (u16)(pitch << octave);
    return (u16)((int)pitch >> -octave);
}

