/* Relocation of a pointer field of a loaded bank: the original adds the
 * delta through an int lvalue.  Its stores then alias the banks' int /
 * u32 counts (retail reloads them in the loops) and the field's address
 * keeps its `&' form (a giv of its own, apart from the NULL test's). */
