// FUNC 0x00268990 snd_set_reverb
/* Builds a sceSdEffectAttr {core 0, mode} and applies it to both cores.
 * Variadic: SD_REV_MODE_ECHO and SD_REV_MODE_DELAY (low byte of mode; the
 * high bits are libsd flags) take the delay, ECHO then the feedback, and
 * every mode but OFF then depth L and R (u16).  Callers: music_init
 * (mode 4, depth 0xFFF / 0xFFF), snd_shutdown. */
void snd_set_reverb(int mode, ...)
{
    SpuEffectAttr attr;             /* sp+0x00 */
    va_list ap;                     /* args spilled at sp+0x88 */

    /* va_start after the memset (ap in $v1, not across the call); mode's
     * low byte in mode itself (retail $s0). */
    memset(&attr, 0, sizeof(attr));
    attr.mode = mode;
    mode &= 0xFF;
    va_start(ap, mode);
    if ((u32)(mode - SD_REV_MODE_ECHO) < 2) {       /* echo, delay */
#ifdef BOOT_OLD_GCC
        /* An exact form, not the original: retail reads the first argument
         * at the va_start address (lw 0x88($sp)) before advancing; the
         * bundled va-mips.h's va_arg (load from ap + 8 - 8) gives
         * lw -8($v1).  Same value: one 8-byte slot. */
        attr.delay = *(int *)ap;
        ap += 8;
#else
        attr.delay = va_arg(ap, int);
#endif
    }
    if (mode == SD_REV_MODE_ECHO)
        attr.feedback = va_arg(ap, int);
    if (mode != SD_REV_MODE_OFF) {
        attr.depth_L = (u16)va_arg(ap, int);
        attr.depth_R = (u16)va_arg(ap, int);
    }
    va_end(ap);
    spu_state_set_effect(&g_00302698, &attr, &attr);
}

