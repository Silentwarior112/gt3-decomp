// FUNC 0x00268C40 seq_note_on
/* Note-on for track t of a sequence (caller: u124's track interpreter
 * 0x00268ED8).  Program = bank->programs[t->program]; volume = track volume
 * * program volume * velocity curve.  Every zone of the program whose key
 * range holds the note gets a free channel (round-robin search from the
 * last one, 47 tries; none -> that zone is skipped): pan = track pan +
 * program pan + zone pan - 0x80 clamped to 0..0x7F, volume * zone volume
 * (squared >> 14 for the pan law), pitch from the note plus the bend scaled
 * by the zone's bend range, and a voice is started on the channel. */
void seq_note_on(Sequence *seq, SeqTrack *t, int note, int velocity, int duration)
{
    /* vol before prog_pan (their spill slots, 0x28 / 0x2C); the voice is
     * started inside the channel search (retail's found block sits in the
     * loop).  Open: registers of zone / &g_002FF958 / the indices
     * (retail zone $a3, %hi $a0, idx $a2, tries $a1). */
    InstBank *bank = seq->bank;
    InstProgram *prog = bank->programs[t->program];
    int vol = (((t->volScaled * prog->vol) >> 14) * g_00345F10[velocity]) >> 14;
    int prog_pan = t->pan + prog->pan;
    int j;
    SndVoiceParam param;

    for (j = 0; j < prog->nzones; j++) {
        InstZone *zone = &bank->zones[prog->zone[j]];
        int idx, tries;
        SeqChannel *ch;

        if (note < zone->lo_note || zone->hi_note < note)
            continue;

        idx = g_002FF958.nextChannel;
        ch = &g_002FF958.ch[idx];
        for (tries = 0; tries < SEQ_NUM_CHANNELS; tries++) {
            idx++;
            ch++;
            if (idx == SEQ_NUM_CHANNELS) {
                idx = 0;
                ch = &g_002FF958.ch[0];
            }
            if (ch->voice < 0) {
                int pitch, pan, zone_vol;
                s16 bend;

                pitch = note * SEMITONE;
                g_002FF958.nextChannel = idx;
                zone_vol = (vol * zone->vol) >> 14;
                pan = prog_pan + zone->pan - 0x80;
                if (pan < 0)
                    pan = 0;
                else if (!(pan < 0x80))
                    pan = 0x7F;
                bend = t->bend;
                ch->note = note;
                ch->velocity = velocity;
                ch->lastBend = bend;
                ch->seq = seq;
                ch->remain = duration + seq->ticks;
                ch->lastVol = t->volScaled;
                ch->track = t;
                ch->prog = prog;
                ch->zone = zone;
                ch->lastPan = t->pan;
                param.adsr = zone->adsr;
                param.addr = zone->addr;
                param.priority = zone->prio;
                param.unk_10 = zone->unk_0A;
                param.flags = zone->flags;
                if (bend != 0)
                    pitch += (bend * ((bend > 0) ? zone->bend_up : zone->bend_down)) >> 5;
                param.pitch = snd_note_to_pitch(pitch, zone->base_note);
                snd_pan_volume(param.vol.lr, (zone_vol * zone_vol) >> 14, pan);
                snd_play_voice(&ch->voice, &param);
                break;
            }
        }
    }
}
